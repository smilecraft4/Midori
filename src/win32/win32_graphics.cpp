// One debug texture: when windows show different atlases in a frame, the last to ask wins.
std::uint64_t GraphicsTileAtlasDebugTexture(TileAtlas atlas) noexcept {
    ZoneScopedN("GraphicsTileAtlasDebugTexture");
    GraphicsState& state = gGraphicsState;
    MIDORI_ASSERT(atlas < kTileAtlasMax && state.tilePools[atlas], "atlas {} not created", atlas);
    state.tileAtlasDebugAtlas = atlas;
    if (!state.tileAtlasDebug) {
        const CD3DX12_HEAP_PROPERTIES heap(D3D12_HEAP_TYPE_DEFAULT);
        const CD3DX12_RESOURCE_DESC desc = CD3DX12_RESOURCE_DESC::Tex2D(
            kTileFormat, UINT64{kTileAtlasDebugColumns} * kTileTexels, kTileAtlasDebugRows * kTileTexels, 1, 1);
        if (const HRESULT hr = state.device->CreateCommittedResource(&heap, D3D12_HEAP_FLAG_NONE, &desc,
                                                                     D3D12_RESOURCE_STATE_PIXEL_SHADER_RESOURCE,
                                                                     nullptr, IID_PPV_ARGS(&state.tileAtlasDebug));
            FAILED(hr)) {
            LogHresult("ID3D12Device::CreateCommittedResource", hr);
            return 0;
        }
        state.device->CreateShaderResourceView(state.tileAtlasDebug, nullptr, ViewCpu(kTileAtlasDebugView));
    }
    state.tileAtlasDebugRequested = true;
    return ViewGpu(kTileAtlasDebugView).ptr;
}

Result<void> GraphicsTilesDownload(std::span<const TileAtlasCell> cells, std::span<std::byte> pixels) noexcept {
    ZoneScopedN("GraphicsTilesDownload");
    MIDORI_ASSERT(pixels.size() == cells.size() * TileBytes(kTilePixelFormat), "{} bytes for {} tiles", pixels.size(),
                  cells.size());
    GraphicsState& state = gGraphicsState;
    if (cells.empty()) {
        return {};
    }
    const auto readback = TileBufferCreate(D3D12_HEAP_TYPE_READBACK, pixels.size());
    if (!readback) {
        return std::unexpected(readback.error());
    }

    ListBeginAndWait();
    state.list->SetDescriptorHeaps(1, &state.views);
    {
        // GPU zones record timestamp queries into the list, so they must close before it does.
        TracyD3D12NamedZone(state.gpuProfiler, gpuSaveZone, state.list, "GpuTilesDownload", true);
        RecordHistory();
        RecordTileCreates();
        RecordTileUploads();
        RecordStroke();
        RecordTileMips();
        RecordComposites();
        TilePoolsTransition(D3D12_RESOURCE_STATE_PIXEL_SHADER_RESOURCE, D3D12_RESOURCE_STATE_COPY_SOURCE);
        for (std::size_t i = 0; i < cells.size(); ++i) {
            TileCopyFromCell(cells[i], *readback, i * TileBytes(kTilePixelFormat));
        }
        TilePoolsTransition(D3D12_RESOURCE_STATE_COPY_SOURCE, D3D12_RESOURCE_STATE_PIXEL_SHADER_RESOURCE);
    }
    ListExecuteAndWait();

    void* mapped = nullptr;
    const D3D12_RANGE read{.Begin = 0, .End = pixels.size()};
    if (const HRESULT hr = (*readback)->Map(0, &read, &mapped); FAILED(hr)) {
        LogHresult("ID3D12Resource::Map", hr);
        (*readback)->Release();
        return std::unexpected(Error::GraphicsTransferFailed);
    }
    std::memcpy(pixels.data(), mapped, pixels.size());
    const D3D12_RANGE noWrite{.Begin = 0, .End = 0};
    (*readback)->Unmap(0, &noWrite);
    (*readback)->Release();
    return {};
}

DWORD GraphicsFrameWaitables(std::span<HANDLE, kWindowMax> handles, std::span<Window, kWindowMax> windows) noexcept {
    ZoneScopedN("GraphicsFrameWaitables");
    DWORD count = 0;
    for (Window window = 0; window < kWindowMax; ++window) {
        const Win32SwapChain& slot = gGraphicsState.windows[window];
        if (slot.swapChain && slot.needsFrame && !slot.frameReady && slot.width > 0 && slot.height > 0) {
            handles[count] = slot.frameWait;
            windows[count] = window;
            ++count;
        }
    }
    return count;
}

void GraphicsWindowFrameAcquired(Window window) noexcept {
    MIDORI_ASSERT(WindowValid(window), "frame acquired for invalid window {}", window);
    gGraphicsState.windows[window].frameReady = true;
}

Result<void> GraphicsWindowResize(Window window, UINT width, UINT height) noexcept {
    ZoneScopedN("GraphicsWindowResize");
    // WM_SIZE also arrives during CreateWindowExW, before GraphicsWindowInit.
    if (!WindowValid(window)) {
        return {};
    }
    Win32SwapChain& slot = gGraphicsState.windows[window];
    slot.width = width;
    slot.height = height;
    if (width == 0 || height == 0) {
        return {};
    }

    // Restoring from minimized, or a DPI change that kept the size, needs no new buffers.
    if (width != slot.bufferWidth || height != slot.bufferHeight) {
        ZoneScopedN("GraphicsResizeBuffers");
        // ResizeBuffers needs every reference to the buffers gone, the GPU's included.
        WaitIdle();
        for (ID3D12Resource*& buffer : slot.buffers) {
            Release(buffer);
        }
        if (const HRESULT hr = slot.swapChain->ResizeBuffers(kSwapChainBufferCount, width, height, DXGI_FORMAT_UNKNOWN,
                                                             kSwapChainFlags);
            FAILED(hr)) {
            LogHresult("IDXGISwapChain::ResizeBuffers", hr);
            return std::unexpected(Error::GraphicsDeviceLost);
        }
        slot.bufferWidth = width;
        slot.bufferHeight = height;
        if (const auto acquired = AcquireBuffers(window); !acquired) {
            return std::unexpected(acquired.error());
        }
    }

    slot.needsFrame = true;
    return GraphicsWindowPresent(window);
}

