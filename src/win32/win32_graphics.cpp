Result<void> GraphicsInit(GraphicsInitInfo initInfo) noexcept {
    ZoneScopedN("GraphicsInit");
    GraphicsState& state = gGraphicsState;
    const auto fail = [](const char* what, HRESULT hr) {
        LogHresult(what, hr);
        GraphicsTerminate();
        return std::unexpected(Error::GraphicsInitFailed);
    };

    if (initInfo.debugLayer) {
        ZoneScopedN("D3D12EnableDebugLayer");
        ID3D12Debug* debug = nullptr;
        if (const HRESULT hr = D3D12GetDebugInterface(IID_PPV_ARGS(&debug)); SUCCEEDED(hr)) {
            debug->EnableDebugLayer();
            debug->Release();
        } else {
            MIDORI_LOG_WARN("D3D12 debug layer unavailable: {:#010x}", static_cast<std::uint32_t>(hr));
        }
    }

    {
        ZoneScopedN("CreateDXGIFactory2");
        const UINT factoryFlags = initInfo.debugLayer ? DXGI_CREATE_FACTORY_DEBUG : 0;
        if (const HRESULT hr = CreateDXGIFactory2(factoryFlags, IID_PPV_ARGS(&state.factory)); FAILED(hr)) {
            return fail("CreateDXGIFactory2", hr);
        }
    }
    // The default adapter is the one the user's Windows graphics settings pick for this app, which
    // keeps laptops on the integrated GPU unless told otherwise.
    {
        ZoneScopedN("D3D12CreateDevice");
        if (const HRESULT hr = D3D12CreateDevice(nullptr, D3D_FEATURE_LEVEL_12_0, IID_PPV_ARGS(&state.device));
            FAILED(hr)) {
            return fail("D3D12CreateDevice", hr);
        }
    }
    if (const HRESULT hr =
            state.factory->EnumAdapterByLuid(state.device->GetAdapterLuid(), IID_PPV_ARGS(&state.adapter));
        FAILED(hr)) {
        LogHresult("IDXGIFactory4::EnumAdapterByLuid", hr);
        state.adapter = nullptr;
    }

    const D3D12_COMMAND_QUEUE_DESC queueDesc{.Type = D3D12_COMMAND_LIST_TYPE_DIRECT};
    if (const HRESULT hr = state.device->CreateCommandQueue(&queueDesc, IID_PPV_ARGS(&state.queue)); FAILED(hr)) {
        return fail("ID3D12Device::CreateCommandQueue", hr);
    }
    for (ID3D12CommandAllocator*& allocator : state.allocators) {
        if (const HRESULT hr =
                state.device->CreateCommandAllocator(D3D12_COMMAND_LIST_TYPE_DIRECT, IID_PPV_ARGS(&allocator));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateCommandAllocator", hr);
        }
    }
    if (const HRESULT hr = state.device->CreateCommandList(0, D3D12_COMMAND_LIST_TYPE_DIRECT, state.allocators[0],
                                                           nullptr, IID_PPV_ARGS(&state.list));
        FAILED(hr)) {
        return fail("ID3D12Device::CreateCommandList", hr);
    }
    // Created open; Submit expects it closed.
    state.list->Close();
    {
        // Allocates its query heap and readback buffer even while no profiler is connected.
        ZoneScopedN("TracyD3D12Context");
        state.gpuProfiler = TracyD3D12Context(state.device, state.queue);
        if (state.gpuProfiler) {
            [[maybe_unused]] constexpr std::string_view kName = "Main queue"; // unused without TRACY_ENABLE
            TracyD3D12ContextName(state.gpuProfiler, kName.data(), static_cast<std::uint16_t>(kName.size()));
        }
    }
    if (const HRESULT hr = state.device->CreateFence(0, D3D12_FENCE_FLAG_NONE, IID_PPV_ARGS(&state.fence));
        FAILED(hr)) {
        return fail("ID3D12Device::CreateFence", hr);
    }

    const D3D12_DESCRIPTOR_HEAP_DESC rtvDesc{
        .Type = D3D12_DESCRIPTOR_HEAP_TYPE_RTV,
        .NumDescriptors = kWindowMax * kSwapChainBufferCount,
    };
    if (const HRESULT hr = state.device->CreateDescriptorHeap(&rtvDesc, IID_PPV_ARGS(&state.rtvs)); FAILED(hr)) {
        return fail("ID3D12Device::CreateDescriptorHeap", hr);
    }
    state.rtvIncrement = state.device->GetDescriptorHandleIncrementSize(D3D12_DESCRIPTOR_HEAP_TYPE_RTV);

    {
        ZoneScopedN("CreateTilePipeline");
        // The root signature tile.vs.hlsl embeds (TILE_ROOT_SIGNATURE).
        if (const HRESULT hr =
                state.device->CreateRootSignature(0, tile_vs, sizeof(tile_vs), IID_PPV_ARGS(&state.tileRootSignature));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateRootSignature", hr);
        }

        // No depth: the premultiplied canvas goes over its background.
        D3D12_GRAPHICS_PIPELINE_STATE_DESC desc{};
        desc.pRootSignature = state.tileRootSignature;
        desc.VS = {.pShaderBytecode = tile_vs, .BytecodeLength = sizeof(tile_vs)};
        desc.PS = {.pShaderBytecode = tile_ps, .BytecodeLength = sizeof(tile_ps)};
        desc.BlendState = CD3DX12_BLEND_DESC(D3D12_DEFAULT);
        D3D12_RENDER_TARGET_BLEND_DESC& blend = desc.BlendState.RenderTarget[0];
        blend.BlendEnable = TRUE;
        blend.SrcBlend = D3D12_BLEND_ONE;
        blend.DestBlend = D3D12_BLEND_INV_SRC_ALPHA;
        blend.BlendOp = D3D12_BLEND_OP_ADD;
        blend.SrcBlendAlpha = D3D12_BLEND_ONE;
        blend.DestBlendAlpha = D3D12_BLEND_INV_SRC_ALPHA;
        blend.BlendOpAlpha = D3D12_BLEND_OP_ADD;
        desc.SampleMask = D3D12_DEFAULT_SAMPLE_MASK;
        desc.RasterizerState = CD3DX12_RASTERIZER_DESC(D3D12_DEFAULT);
        desc.RasterizerState.CullMode = D3D12_CULL_MODE_NONE;
        desc.PrimitiveTopologyType = D3D12_PRIMITIVE_TOPOLOGY_TYPE_TRIANGLE;
        desc.NumRenderTargets = 1;
        desc.RTVFormats[0] = kSwapChainFormat;
        desc.SampleDesc.Count = 1;
        if (const HRESULT hr = state.device->CreateGraphicsPipelineState(&desc, IID_PPV_ARGS(&state.tilePipeline));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateGraphicsPipelineState", hr);
        }

        // Written by the CPU every frame, so an upload heap mapped for its whole life, one part per frame in flight.
        const CD3DX12_HEAP_PROPERTIES heap(D3D12_HEAP_TYPE_UPLOAD);
        const CD3DX12_RESOURCE_DESC bufferDesc = CD3DX12_RESOURCE_DESC::Buffer(
            std::size_t{kGraphicsFramesInFlight} * kPageTableEntriesMax * sizeof(std::uint32_t));
        if (const HRESULT hr = state.device->CreateCommittedResource(&heap, D3D12_HEAP_FLAG_NONE, &bufferDesc,
                                                                     D3D12_RESOURCE_STATE_GENERIC_READ, nullptr,
                                                                     IID_PPV_ARGS(&state.pageTables));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateCommittedResource", hr);
        }
        void* mapped = nullptr;
        const D3D12_RANGE noRead{.Begin = 0, .End = 0};
        if (const HRESULT hr = state.pageTables->Map(0, &noRead, &mapped); FAILED(hr)) {
            return fail("ID3D12Resource::Map", hr);
        }
        state.pageTablesMapped = static_cast<std::uint32_t*>(mapped);
    }

    {
        ZoneScopedN("CreateTilePool");
        const D3D12_DESCRIPTOR_HEAP_DESC viewsDesc{
            .Type = D3D12_DESCRIPTOR_HEAP_TYPE_CBV_SRV_UAV,
            .NumDescriptors = kUiTextureFirstView + kUiTextureMax,
            .Flags = D3D12_DESCRIPTOR_HEAP_FLAG_SHADER_VISIBLE,
        };
        if (const HRESULT hr = state.device->CreateDescriptorHeap(&viewsDesc, IID_PPV_ARGS(&state.views)); FAILED(hr)) {
            return fail("ID3D12Device::CreateDescriptorHeap", hr);
        }
        state.viewIncrement = state.device->GetDescriptorHandleIncrementSize(D3D12_DESCRIPTOR_HEAP_TYPE_CBV_SRV_UAV);

        for (TileAtlas atlas = 0; atlas < kTileAtlasMax; ++atlas) {
            state.device->CreateShaderResourceView(nullptr, &kTilePoolSrvDesc, ViewCpu(kTilePoolFirstView + atlas));
            state.device->CreateUnorderedAccessView(nullptr, nullptr, &kTilePoolUavDesc,
                                                    ViewCpu(kTilePoolFirstUav + atlas));
        }
        if (!TilePoolCreate(0)) {
            GraphicsTerminate();
            return std::unexpected(Error::GraphicsInitFailed);
        }

        // The clear cell: transparent black.
        const D3D12_RESOURCE_DESC poolDesc = state.tilePools[0]->GetDesc();
        D3D12_PLACED_SUBRESOURCE_FOOTPRINT footprint{};
        UINT64 uploadSize = 0;
        state.device->GetCopyableFootprints(&poolDesc, 0, 1, 0, &footprint, nullptr, nullptr, &uploadSize);
        ID3D12Resource* upload = nullptr;
        const CD3DX12_HEAP_PROPERTIES uploadHeap(D3D12_HEAP_TYPE_UPLOAD);
        const CD3DX12_RESOURCE_DESC uploadDesc = CD3DX12_RESOURCE_DESC::Buffer(uploadSize);
        if (const HRESULT hr = state.device->CreateCommittedResource(&uploadHeap, D3D12_HEAP_FLAG_NONE, &uploadDesc,
                                                                     D3D12_RESOURCE_STATE_GENERIC_READ, nullptr,
                                                                     IID_PPV_ARGS(&upload));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateCommittedResource", hr);
        }
        void* mapped = nullptr;
        const D3D12_RANGE noRead{.Begin = 0, .End = 0};
        if (const HRESULT hr = upload->Map(0, &noRead, &mapped); FAILED(hr)) {
            upload->Release();
            return fail("ID3D12Resource::Map", hr);
        }
        std::memset(mapped, 0, static_cast<std::size_t>(uploadSize));
        upload->Unmap(0, nullptr);

        state.list->Reset(state.allocators[0], nullptr);
        TilePoolsTransition(D3D12_RESOURCE_STATE_PIXEL_SHADER_RESOURCE, D3D12_RESOURCE_STATE_COPY_DEST);
        const CD3DX12_TEXTURE_COPY_LOCATION dst = TilePoolLocation(kTileAtlasCellClear);
        const CD3DX12_TEXTURE_COPY_LOCATION src(upload, footprint);
        state.list->CopyTextureRegion(&dst, 0, 0, 0, &src, nullptr);
        TilePoolsTransition(D3D12_RESOURCE_STATE_COPY_DEST, D3D12_RESOURCE_STATE_PIXEL_SHADER_RESOURCE);
        state.list->Close();
        ID3D12CommandList* lists[] = {state.list};
        state.queue->ExecuteCommandLists(1, lists);
        state.queue->Signal(state.fence, ++state.fenceValue);
        state.allocatorFences[0] = state.fenceValue;
        WaitIdle();
        upload->Release();
    }

    {
        // Mapped for their whole life: an upload heap is write-only for the CPU, a readback heap is read only after
        // the fence of the copy that wrote it.
        ZoneScopedN("CreateTileTransferSlots");
        const auto uploads = TileBufferCreate(D3D12_HEAP_TYPE_UPLOAD, std::size_t{kTileTransferSlots} * kTileSlotBytes);
        const auto downloads =
            TileBufferCreate(D3D12_HEAP_TYPE_READBACK, std::size_t{kTileTransferSlots} * kTileSlotBytes);
        state.tileUploads = uploads.value_or(nullptr);
        state.tileDownloads = downloads.value_or(nullptr);
        if (!uploads || !downloads) {
            GraphicsTerminate();
            return std::unexpected(Error::GraphicsInitFailed);
        }
        void* mapped = nullptr;
        const D3D12_RANGE noRead{.Begin = 0, .End = 0};
        if (const HRESULT hr = state.tileUploads->Map(0, &noRead, &mapped); FAILED(hr)) {
            return fail("ID3D12Resource::Map", hr);
        }
        state.tileUploadsMapped = static_cast<std::byte*>(mapped);
        const D3D12_RANGE all{.Begin = 0, .End = std::size_t{kTileTransferSlots} * kTileSlotBytes};
        if (const HRESULT hr = state.tileDownloads->Map(0, &all, &mapped); FAILED(hr)) {
            return fail("ID3D12Resource::Map", hr);
        }
        state.tileDownloadsMapped = static_cast<std::byte*>(mapped);
    }

    {
        ZoneScopedN("CreateBrushOutlinePipeline");
        if (const HRESULT hr = state.device->CreateRootSignature(0, brush_outline_vs, sizeof(brush_outline_vs),
                                                                 IID_PPV_ARGS(&state.outlineRootSignature));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateRootSignature", hr);
        }
        // Inverts what is below where the shader's coverage is 1: c * (1 - dst) + dst * (1 - c). Alpha is kept, so the
        // composition with the desktop does not change.
        D3D12_GRAPHICS_PIPELINE_STATE_DESC desc{};
        desc.pRootSignature = state.outlineRootSignature;
        desc.VS = {.pShaderBytecode = brush_outline_vs, .BytecodeLength = sizeof(brush_outline_vs)};
        desc.PS = {.pShaderBytecode = brush_outline_ps, .BytecodeLength = sizeof(brush_outline_ps)};
        desc.BlendState = CD3DX12_BLEND_DESC(D3D12_DEFAULT);
        D3D12_RENDER_TARGET_BLEND_DESC& blend = desc.BlendState.RenderTarget[0];
        blend.BlendEnable = TRUE;
        blend.SrcBlend = D3D12_BLEND_INV_DEST_COLOR;
        blend.DestBlend = D3D12_BLEND_INV_SRC_COLOR;
        blend.BlendOp = D3D12_BLEND_OP_ADD;
        blend.SrcBlendAlpha = D3D12_BLEND_ZERO;
        blend.DestBlendAlpha = D3D12_BLEND_ONE;
        blend.BlendOpAlpha = D3D12_BLEND_OP_ADD;
        blend.RenderTargetWriteMask =
            D3D12_COLOR_WRITE_ENABLE_RED | D3D12_COLOR_WRITE_ENABLE_GREEN | D3D12_COLOR_WRITE_ENABLE_BLUE;
        desc.SampleMask = D3D12_DEFAULT_SAMPLE_MASK;
        desc.RasterizerState = CD3DX12_RASTERIZER_DESC(D3D12_DEFAULT);
        desc.RasterizerState.CullMode = D3D12_CULL_MODE_NONE;
        desc.PrimitiveTopologyType = D3D12_PRIMITIVE_TOPOLOGY_TYPE_TRIANGLE;
        desc.NumRenderTargets = 1;
        desc.RTVFormats[0] = kSwapChainFormat;
        desc.SampleDesc.Count = 1;
        if (const HRESULT hr = state.device->CreateGraphicsPipelineState(&desc, IID_PPV_ARGS(&state.outlinePipeline));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateGraphicsPipelineState", hr);
        }
    }

    {
        ZoneScopedN("CreateTileMipPipeline");
        if (const HRESULT hr = state.device->CreateRootSignature(0, tile_mip_cs, sizeof(tile_mip_cs),
                                                                 IID_PPV_ARGS(&state.mipRootSignature));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateRootSignature", hr);
        }
        const D3D12_COMPUTE_PIPELINE_STATE_DESC desc{
            .pRootSignature = state.mipRootSignature,
            .CS = {.pShaderBytecode = tile_mip_cs, .BytecodeLength = sizeof(tile_mip_cs)},
        };
        if (const HRESULT hr = state.device->CreateComputePipelineState(&desc, IID_PPV_ARGS(&state.mipPipeline));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateComputePipelineState", hr);
        }
    }

    {
        ZoneScopedN("CreateCompositePipeline");
        if (const HRESULT hr = state.device->CreateRootSignature(0, tile_blend_cs, sizeof(tile_blend_cs),
                                                                 IID_PPV_ARGS(&state.compositeRootSignature));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateRootSignature", hr);
        }
        const D3D12_COMPUTE_PIPELINE_STATE_DESC desc{
            .pRootSignature = state.compositeRootSignature,
            .CS = {.pShaderBytecode = tile_blend_cs, .BytecodeLength = sizeof(tile_blend_cs)},
        };
        if (const HRESULT hr = state.device->CreateComputePipelineState(&desc, IID_PPV_ARGS(&state.compositePipeline));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateComputePipelineState", hr);
        }

        const CD3DX12_HEAP_PROPERTIES heap(D3D12_HEAP_TYPE_UPLOAD);
        const CD3DX12_RESOURCE_DESC bufferDesc = CD3DX12_RESOURCE_DESC::Buffer(
            std::size_t{kGraphicsFramesInFlight} * kCompositeSourcesMax * sizeof(CompositeGpuSource));
        if (const HRESULT hr = state.device->CreateCommittedResource(&heap, D3D12_HEAP_FLAG_NONE, &bufferDesc,
                                                                     D3D12_RESOURCE_STATE_GENERIC_READ, nullptr,
                                                                     IID_PPV_ARGS(&state.compositeSources));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateCommittedResource", hr);
        }
        void* mapped = nullptr;
        const D3D12_RANGE noRead{.Begin = 0, .End = 0};
        if (const HRESULT hr = state.compositeSources->Map(0, &noRead, &mapped); FAILED(hr)) {
            return fail("ID3D12Resource::Map", hr);
        }
        state.compositeSourcesMapped = static_cast<CompositeGpuSource*>(mapped);
    }

    {
        ZoneScopedN("CreateStrokePipeline");
        if (const HRESULT hr = state.device->CreateRootSignature(0, stroke_cs, sizeof(stroke_cs),
                                                                 IID_PPV_ARGS(&state.strokeRootSignature));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateRootSignature", hr);
        }
        const D3D12_COMPUTE_PIPELINE_STATE_DESC desc{
            .pRootSignature = state.strokeRootSignature,
            .CS = {.pShaderBytecode = stroke_cs, .BytecodeLength = sizeof(stroke_cs)},
        };
        if (const HRESULT hr = state.device->CreateComputePipelineState(&desc, IID_PPV_ARGS(&state.strokePipeline));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateComputePipelineState", hr);
        }

        const CD3DX12_HEAP_PROPERTIES heap(D3D12_HEAP_TYPE_UPLOAD);
        const CD3DX12_RESOURCE_DESC bufferDesc =
            CD3DX12_RESOURCE_DESC::Buffer(std::size_t{kGraphicsFramesInFlight} * kStrokeDabMax * sizeof(StrokeDab));
        if (const HRESULT hr = state.device->CreateCommittedResource(&heap, D3D12_HEAP_FLAG_NONE, &bufferDesc,
                                                                     D3D12_RESOURCE_STATE_GENERIC_READ, nullptr,
                                                                     IID_PPV_ARGS(&state.strokeDabs));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateCommittedResource", hr);
        }
        void* mapped = nullptr;
        const D3D12_RANGE noRead{.Begin = 0, .End = 0};
        if (const HRESULT hr = state.strokeDabs->Map(0, &noRead, &mapped); FAILED(hr)) {
            return fail("ID3D12Resource::Map", hr);
        }
        state.strokeDabsMapped = static_cast<StrokeDab*>(mapped);

        const CD3DX12_RESOURCE_DESC brushDesc =
            CD3DX12_RESOURCE_DESC::Buffer(std::size_t{kGraphicsFramesInFlight} * kStrokeBrushStride);
        if (const HRESULT hr = state.device->CreateCommittedResource(&heap, D3D12_HEAP_FLAG_NONE, &brushDesc,
                                                                     D3D12_RESOURCE_STATE_GENERIC_READ, nullptr,
                                                                     IID_PPV_ARGS(&state.strokeBrush));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateCommittedResource", hr);
        }
        if (const HRESULT hr = state.strokeBrush->Map(0, &noRead, &mapped); FAILED(hr)) {
            return fail("ID3D12Resource::Map", hr);
        }
        state.strokeBrushMapped = static_cast<std::byte*>(mapped);
        for (UINT i = 0; i < kToolShadersMax * kMdslTexturesMax; ++i) {
            state.device->CreateShaderResourceView(nullptr, &kBrushTextureSrvDesc, ViewCpu(kBrushTextureFirstView + i));
        }
    }

    {
        ZoneScopedN("CreateTransformPipeline");
        if (const HRESULT hr = state.device->CreateRootSignature(0, transform_cs, sizeof(transform_cs),
                                                                 IID_PPV_ARGS(&state.transformRootSignature));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateRootSignature", hr);
        }
        const D3D12_COMPUTE_PIPELINE_STATE_DESC desc{
            .pRootSignature = state.transformRootSignature,
            .CS = {.pShaderBytecode = transform_cs, .BytecodeLength = sizeof(transform_cs)},
        };
        if (const HRESULT hr = state.device->CreateComputePipelineState(&desc, IID_PPV_ARGS(&state.transformPipeline));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateComputePipelineState", hr);
        }
    }

    {
        ZoneScopedN("CreateHistoryPipeline");
        if (const HRESULT hr = state.device->CreateRootSignature(0, history_cs, sizeof(history_cs),
                                                                 IID_PPV_ARGS(&state.historyRootSignature));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateRootSignature", hr);
        }
        const D3D12_COMPUTE_PIPELINE_STATE_DESC desc{
            .pRootSignature = state.historyRootSignature,
            .CS = {.pShaderBytecode = history_cs, .BytecodeLength = sizeof(history_cs)},
        };
        if (const HRESULT hr = state.device->CreateComputePipelineState(&desc, IID_PPV_ARGS(&state.historyPipeline));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateComputePipelineState", hr);
        }

        // Buffers start in COMMON and are promoted to UNORDERED_ACCESS by their first use in each list.
        const CD3DX12_HEAP_PROPERTIES storeHeap(D3D12_HEAP_TYPE_DEFAULT);
        const CD3DX12_RESOURCE_DESC storeDesc = CD3DX12_RESOURCE_DESC::Buffer(
            std::size_t{kHistorySlotsMax} * kHistoryBlockBytes, D3D12_RESOURCE_FLAG_ALLOW_UNORDERED_ACCESS);
        if (const HRESULT hr = state.device->CreateCommittedResource(&storeHeap, D3D12_HEAP_FLAG_NONE, &storeDesc,
                                                                     D3D12_RESOURCE_STATE_COMMON, nullptr,
                                                                     IID_PPV_ARGS(&state.historyStore));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateCommittedResource", hr);
        }

        const CD3DX12_HEAP_PROPERTIES opsHeap(D3D12_HEAP_TYPE_UPLOAD);
        const CD3DX12_RESOURCE_DESC opsDesc = CD3DX12_RESOURCE_DESC::Buffer(std::size_t{kGraphicsFramesInFlight}
                                                                            * kHistorySlotsMax * sizeof(HistoryGpuOp));
        if (const HRESULT hr = state.device->CreateCommittedResource(&opsHeap, D3D12_HEAP_FLAG_NONE, &opsDesc,
                                                                     D3D12_RESOURCE_STATE_GENERIC_READ, nullptr,
                                                                     IID_PPV_ARGS(&state.historyOps));
            FAILED(hr)) {
            return fail("ID3D12Device::CreateCommittedResource", hr);
        }
        void* mapped = nullptr;
        const D3D12_RANGE noRead{.Begin = 0, .End = 0};
        if (const HRESULT hr = state.historyOps->Map(0, &noRead, &mapped); FAILED(hr)) {
            return fail("ID3D12Resource::Map", hr);
        }
        state.historyOpsMapped = static_cast<HistoryGpuOp*>(mapped);
    }

    {
        ZoneScopedN("DCompositionCreateDevice2");
        if (const HRESULT hr = DCompositionCreateDevice2(nullptr, IID_PPV_ARGS(&state.composition)); FAILED(hr)) {
            return fail("DCompositionCreateDevice2", hr);
        }
    }
    return {};
}

Result<void> GraphicsUpdate() noexcept {
    ZoneScopedN("GraphicsUpdate");
    std::array<Window, kWindowMax> ready{};
    std::size_t count = 0;
    for (Window window = 0; window < kWindowMax; ++window) {
        Win32SwapChain& slot = gGraphicsState.windows[window];
        if (!slot.swapChain || !slot.needsFrame || slot.width == 0 || slot.height == 0) {
            continue;
        }
        if (!slot.frameReady && WaitForSingleObjectEx(slot.frameWait, 0, TRUE) == WAIT_OBJECT_0) {
            slot.frameReady = true;
        }
        if (slot.frameReady) {
            ready[count++] = window;
        }
    }
    if (count == 0) {
        return {};
    }
    return Submit(std::span(ready.data(), count));
}

void GraphicsTerminate() noexcept {
    ZoneScopedN("GraphicsTerminate");
    GraphicsState& state = gGraphicsState;
    if (state.fence) {
        WaitIdle();
    }
    for (Win32SwapChain& slot : state.windows) {
        ReleaseWindow(slot);
    }
    // Drains its pending queries, so after WaitIdle and before the queue goes.
    if (state.gpuProfiler) {
        TracyD3D12Destroy(state.gpuProfiler);
        state.gpuProfiler = nullptr;
    }
    Release(state.composition);
    Release(state.historyOps);
    Release(state.historyStore);
    Release(state.historyPipeline);
    Release(state.historyRootSignature);
    Release(state.compositeSources);
    Release(state.compositePipeline);
    Release(state.compositeRootSignature);
    Release(state.strokeDabs);
    Release(state.strokeBrush);
    for (auto& textures : state.brushTextures) {
        for (ID3D12Resource*& texture : textures) {
            Release(texture);
        }
    }
    Release(state.transformPipeline);
    Release(state.transformRootSignature);
    if (gBrushCompile.thread.joinable()) {
        gBrushCompile.thread.join();
    }
    Release(gBrushCompile.pipeline);
    for (std::uint32_t i = 0; i < kToolShadersMax; ++i) {
        Release(state.strokeBrushReady[i]);
        Release(state.strokeBrushPipelines[i]);
    }
    Release(state.strokeBrushRetired);
    Release(state.strokePipeline);
    Release(state.strokeRootSignature);
    Release(state.mipPipeline);
    Release(state.mipRootSignature);
    Release(state.tileAtlasDebug);
    Release(state.tileUploads);
    Release(state.tileDownloads);
    for (ID3D12Resource*& pool : state.tilePools) {
        Release(pool);
    }
    Release(state.views);
    Release(state.outlinePipeline);
    Release(state.outlineRootSignature);
    Release(state.pageTables);
    Release(state.tilePipeline);
    Release(state.tileRootSignature);
    Release(state.rtvs);
    Release(state.fence);
    Release(state.list);
    for (ID3D12CommandAllocator*& allocator : state.allocators) {
        Release(allocator);
    }
    Release(state.queue);
    Release(state.device);
    Release(state.adapter);
    Release(state.factory);
    state = {};
}

Result<void> GraphicsWindowInit(GraphicsWindowInitInfo initInfo) noexcept {
    ZoneScopedN("GraphicsWindowInit");
    const Window window = initInfo.window;
    if (window >= kWindowMax || !gPlatformState.windows[window].hwnd || gGraphicsState.windows[window].swapChain) {
        return std::unexpected(Error::WindowInvalid);
    }
    GraphicsState& state = gGraphicsState;
    Win32SwapChain& slot = state.windows[window];
    const auto fail = [&slot](const char* what, HRESULT hr) {
        LogHresult(what, hr);
        ReleaseWindow(slot);
        return std::unexpected(Error::GraphicsWindowInitFailed);
    };

    const HWND hwnd = gPlatformState.windows[window].hwnd;
    RECT client{};
    GetClientRect(hwnd, &client);
    slot.width = static_cast<UINT>(client.right - client.left);
    slot.height = static_cast<UINT>(client.bottom - client.top);
    // Buffers cannot be empty: a window created minimized gets 1x1 until its first real WM_SIZE.
    slot.bufferWidth = std::max(slot.width, 1u);
    slot.bufferHeight = std::max(slot.height, 1u);

    // Composition swap chains must stretch; buffers matching the client area make that 1:1.
    const DXGI_SWAP_CHAIN_DESC1 desc{
        .Width = slot.bufferWidth,
        .Height = slot.bufferHeight,
        .Format = kSwapChainFormat,
        .SampleDesc = {.Count = 1},
        .BufferUsage = DXGI_USAGE_RENDER_TARGET_OUTPUT,
        .BufferCount = kSwapChainBufferCount,
        .Scaling = DXGI_SCALING_STRETCH,
        .SwapEffect = DXGI_SWAP_EFFECT_FLIP_DISCARD,
        .AlphaMode = DXGI_ALPHA_MODE_PREMULTIPLIED,
        .Flags = kSwapChainFlags,
    };
    IDXGISwapChain1* swapChain1 = nullptr;
    {
        ZoneScopedN("CreateSwapChainForComposition");
        if (const HRESULT hr = state.factory->CreateSwapChainForComposition(state.queue, &desc, nullptr, &swapChain1);
            FAILED(hr)) {
            return fail("IDXGIFactory2::CreateSwapChainForComposition", hr);
        }
    }
    const HRESULT queried = swapChain1->QueryInterface(IID_PPV_ARGS(&slot.swapChain));
    swapChain1->Release();
    if (FAILED(queried)) {
        return fail("IDXGISwapChain1::QueryInterface(IDXGISwapChain4)", queried);
    }

    // One frame queued at most: the waitable then signals when the next frame can start.
    slot.swapChain->SetMaximumFrameLatency(1);
    slot.frameWait = slot.swapChain->GetFrameLatencyWaitableObject();
    if (const auto acquired = AcquireBuffers(window); !acquired) {
        ReleaseWindow(slot);
        return std::unexpected(acquired.error());
    }

    {
        ZoneScopedN("DCompositionBind");
        if (const HRESULT hr = state.composition->CreateTargetForHwnd(hwnd, TRUE, &slot.target); FAILED(hr)) {
            return fail("IDCompositionDesktopDevice::CreateTargetForHwnd", hr);
        }
        if (const HRESULT hr = state.composition->CreateVisual(&slot.visual); FAILED(hr)) {
            return fail("IDCompositionDevice2::CreateVisual", hr);
        }
        slot.visual->SetContent(slot.swapChain);
        slot.target->SetRoot(slot.visual);
        if (const HRESULT hr = state.composition->Commit(); FAILED(hr)) {
            return fail("IDCompositionDevice2::Commit", hr);
        }
    }

    if (initInfo.ui) {
        ZoneScopedN("ImGui_ImplDX12_Init");
        ImGui::SetCurrentContext(initInfo.ui);
        ImGui_ImplDX12_InitInfo uiInfo{};
        uiInfo.Device = state.device;
        uiInfo.CommandQueue = state.queue;
        uiInfo.NumFramesInFlight = kGraphicsFramesInFlight;
        uiInfo.RTVFormat = kSwapChainFormat;
        uiInfo.DSVFormat = DXGI_FORMAT_UNKNOWN;
        uiInfo.SrvDescriptorHeap = state.views;
        uiInfo.SrvDescriptorAllocFn = UiTextureAlloc;
        uiInfo.SrvDescriptorFreeFn = UiTextureFree;
        ImGui_ImplDX12_Init(&uiInfo);
        slot.ui = initInfo.ui;
        // Up front rather than lazily in ImGui_ImplDX12_NewFrame, so a failure surfaces here.
        if (!ImGui_ImplDX12_CreateDeviceObjects()) {
            MIDORI_LOG_ERROR("ImGui_ImplDX12_CreateDeviceObjects failed");
            ReleaseWindow(slot);
            return std::unexpected(Error::GraphicsWindowInitFailed);
        }
    }

    slot.needsFrame = true;
    return {};
}

Result<void> GraphicsWindowPresent(Window window) noexcept {
    ZoneScopedN("GraphicsWindowPresent");
    if (!WindowValid(window)) {
        return std::unexpected(Error::WindowInvalid);
    }
    Win32SwapChain& slot = gGraphicsState.windows[window];
    if (slot.width == 0 || slot.height == 0) {
        return {};
    }
    if (!slot.frameReady) {
        ZoneScopedN("GraphicsWaitForFrame");
        if (WaitForSingleObjectEx(slot.frameWait, kFrameWaitTimeoutMs, TRUE) != WAIT_OBJECT_0) {
            MIDORI_LOG_WARN("window {}: no frame after {} ms, present skipped", window, kFrameWaitTimeoutMs);
            return {};
        }
        slot.frameReady = true;
    }
    const std::array windows{window};
    return Submit(windows);
}

Result<void> GraphicsWindowTerminate(Window window) noexcept {
    ZoneScopedN("GraphicsWindowTerminate");
    if (window >= kWindowMax) {
        return std::unexpected(Error::WindowInvalid);
    }
    // A window whose GraphicsWindowInit failed or never ran has nothing to release.
    if (!gGraphicsState.windows[window].swapChain) {
        return {};
    }
    WaitIdle();
    ReleaseWindow(gGraphicsState.windows[window]);
    return {};
}

GraphicsMemory GraphicsMemoryGet() noexcept {
    IDXGIAdapter3* adapter = gGraphicsState.adapter;
    DXGI_QUERY_VIDEO_MEMORY_INFO local{};
    DXGI_QUERY_VIDEO_MEMORY_INFO nonLocal{};
    if (!adapter || FAILED(adapter->QueryVideoMemoryInfo(0, DXGI_MEMORY_SEGMENT_GROUP_LOCAL, &local))
        || FAILED(adapter->QueryVideoMemoryInfo(0, DXGI_MEMORY_SEGMENT_GROUP_NON_LOCAL, &nonLocal))) {
        return {};
    }
    return GraphicsMemory{
        .localUsage = local.CurrentUsage,
        .localBudget = local.Budget,
        .nonLocalUsage = nonLocal.CurrentUsage,
        .nonLocalBudget = nonLocal.Budget,
    };
}

